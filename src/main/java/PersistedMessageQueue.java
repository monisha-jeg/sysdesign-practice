import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.Locale;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicBoolean;

import javax.sql.DataSource;

import org.h2.jdbcx.JdbcDataSource;

/**
 * A persisted job queue stored in H2. It models a durable work queue where workers pull
 * queued tasks, process them, and record completion results back to the database.
 */
public class PersistedMessageQueue implements AutoCloseable {
    // The queue is stored in an H2 table so jobs survive process restarts.
    private static final String CREATE_TABLE_SQL = """
            CREATE TABLE IF NOT EXISTS job_queue (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                status VARCHAR(20) NOT NULL DEFAULT 'QUEUED',
                payload VARCHAR(255) NOT NULL,
                result VARCHAR(255),
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """;

    // Inserts a new queued string job.
    private static final String INSERT_SQL =
            "INSERT INTO job_queue (payload, status) VALUES (?, 'QUEUED')";
    // Pulls the oldest available job so the queue behaves in FIFO order.
    private static final String SELECT_NEXT_SQL =
            "SELECT id, payload FROM job_queue WHERE status = 'QUEUED' ORDER BY id LIMIT 1";
    // Updates the job's status and the processed uppercase result.
    private static final String UPDATE_STATUS_SQL =
            "UPDATE job_queue SET status = ?, result = ? WHERE id = ?";
    // Reads the status for a specific payload so tests can confirm per-job completion.
    private static final String JOB_STATUS_SQL =
            "SELECT status, result FROM job_queue WHERE payload = ? ORDER BY id DESC LIMIT 1";

    // The database is the source of truth for queued jobs.
    private final DataSource dataSource;
    // A fixed worker pool processes jobs concurrently.
    private final ExecutorService workers;
    // Shutdown is shared across workers so they can stop cleanly.
    private final AtomicBoolean shutdown = new AtomicBoolean(false);
    // This monitor coordinates wait/notify between workers and the producer.
    private final Object lock = new Object();

    public PersistedMessageQueue(Path databasePath, int workerCount) {
        try {
            // Make sure the directory for the H2 file database exists before connecting.
            Path parentDirectory = databasePath.getParent() == null ? Path.of(".") : databasePath.getParent();
            Files.createDirectories(parentDirectory);

            JdbcDataSource datasource = new JdbcDataSource();
            datasource.setURL("jdbc:h2:file:" + databasePath.toAbsolutePath() + ";AUTO_SERVER=TRUE;DB_CLOSE_DELAY=-1");
            datasource.setUser("sa");
            datasource.setPassword("");

            this.dataSource = datasource;
            initializeSchema();
            this.workers = Executors.newFixedThreadPool(workerCount);

            // Start one worker thread per configured slot.
            for (int i = 0; i < workerCount; i++) {
                workers.submit(this::workerLoop);
            }
        } catch (SQLException | RuntimeException | java.io.IOException e) {
            throw new IllegalStateException("Failed to initialize H2 persisted job queue", e);
        }
    }

    public void submit(String value) {
        // Reject late submissions and null work so the queue remains internally consistent.
        if (shutdown.get()) {
            throw new IllegalStateException("Queue is shut down");
        }
        if (value == null) {
            throw new IllegalArgumentException("Job value cannot be null");
        }

        // Insert the job row and then wake a worker so the processing loop can pick it up.
        try (Connection connection = dataSource.getConnection();
            PreparedStatement insert = connection.prepareStatement(INSERT_SQL, Statement.RETURN_GENERATED_KEYS)) {
            insert.setString(1, value);
            insert.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("Failed to enqueue job in H2", e);
        }

        synchronized (lock) {
            lock.notify();
        }
    }

    public boolean isFinished(String payload) {
        // A job is considered complete only when it has reached the DONE state in the database.
        return "DONE".equalsIgnoreCase(jobStatusForPayload(payload));
    }

    public String jobStatusForPayload(String payload) {
        // Read the latest persisted status for the given payload so callers can inspect job progress.
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(JOB_STATUS_SQL)) {
            statement.setString(1, payload);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return resultSet.getString("status");
                }
                return null;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Failed to read job status for payload", e);
        }
    }

    public String resultForPayload(String payload) {
        // The result is stored alongside the job record, so reading it back is just a simple query.
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(JOB_STATUS_SQL)) {
            statement.setString(1, payload);
            try (ResultSet resultSet = statement.executeQuery()) {
                if (resultSet.next()) {
                    return resultSet.getString("result");
                }
                return null;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("Failed to read job result for payload", e);
        }
    }

    public void shutdown() {
        // Stop accepting new work and wake every waiting worker so they can observe the shutdown signal.
        shutdown.set(true);
        synchronized (lock) {
            lock.notifyAll();
        }
        workers.shutdown();
    }

    private void workerLoop() {
        while (true) {
            Long jobId = null;
            String payload = null;

            synchronized (lock) {
                // Poll the database until work appears, or shutdown starts and there is nothing left to do.
                while (jobId == null && !shutdown.get()) {
                    QueuedJob job = nextQueuedJob();
                    if (job == null) {
                        try {
                            lock.wait(100L);
                        } catch (InterruptedException e) {
                            Thread.currentThread().interrupt();
                            return;
                        }
                        continue;
                    }
                    jobId = job.id();
                    payload = job.payload();
                }
            }

            // If shutdown is set and no jobs remain, this worker ends its loop.
            if (jobId == null && shutdown.get()) {
                return;
            }

            String processedValue = capitalize(payload);
            markStatus(jobId, "DONE", processedValue);
        }
    }

    private QueuedJob nextQueuedJob() {
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(SELECT_NEXT_SQL);
             ResultSet resultSet = statement.executeQuery()) {
            if (resultSet.next()) {
                return new QueuedJob(resultSet.getLong("id"), resultSet.getString("payload"));
            }
            return null;
        } catch (SQLException e) {
            throw new IllegalStateException("Failed to fetch next job from H2", e);
        }
    }

    private void markStatus(long jobId, String status, String result) {
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(UPDATE_STATUS_SQL)) {
            statement.setString(1, status);
            statement.setString(2, result);
            statement.setLong(3, jobId);
            statement.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("Failed to update persisted job status", e);
        }
    }

    private String capitalize(String value) {
        return value.toUpperCase(Locale.ROOT);
    }

    private void initializeSchema() throws SQLException {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.execute(CREATE_TABLE_SQL);
        }
    }

    private record QueuedJob(long id, String payload) {
    }

    @Override
    public void close() {
        shutdown();
    }
}
